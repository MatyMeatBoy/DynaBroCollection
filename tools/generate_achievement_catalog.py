"""Generate static local metadata from checked-in JSON. No network or API access."""
import argparse
import json
from pathlib import Path

# All public DB1 goals have qualified local event contracts. This is not an
# import of the unavailable official RetroAchievements trigger definitions.
DB1_UNQUALIFIED = set()

def literal(value):
    return json.dumps(str(value), ensure_ascii=True)

def generate(root):
    target=root/'games/achievement_catalog'
    target.mkdir(parents=True,exist_ok=True)
    for game in (1,2):
        data=json.loads((root/f'assets/achievements/db{game}.json').read_text(encoding='utf-8'))
        entries=data['achievements']
        ids={e['id'] for e in entries}
        if len(ids)!=len(entries) or any(not isinstance(i,int) or i<=0 or i>0xffffffff for i in ids):
            raise ValueError('Duplicate or invalid achievement ID')
        rows=[]; requires=[]
        for entry in entries:
            dependencies=entry.get('requires_all',[])
            if len(set(dependencies))!=len(dependencies) or any(i not in ids or i==entry['id'] for i in dependencies):
                raise ValueError('Invalid milestone dependency')
            if any(next(e for e in entries if e['id']==i).get('requires_all') for i in dependencies):
                raise ValueError('Nested milestones are unsupported')
            start=len(requires);requires.extend(dependencies)
            qualified=game==2 or entry['id'] not in DB1_UNQUALIFIED
            fields=[str(entry['id'])+'u',literal(entry['title']),literal(entry['description']),str(entry['points'])+'u',literal(entry.get('badge_file_locked','')),literal(entry.get('badge_file_unlocked','')),str(int(qualified)),'0']
            rows.append('    {{'+','.join(fields)+'},'+str(start)+'u,'+str(len(dependencies))+'u}')
        text='/* Generated by tools/generate_achievement_catalog.py; do not edit. */\n'
        text+=f'static const CatalogEntry db{game}_catalog[]={{\n'+',\n'.join(rows)+'\n};\n'
        text+=f'static const uint32_t db{game}_requires[]={{'+','.join(str(i)+'u' for i in (requires or [0]))+'};\n'
        (target/f'db{game}.inc').write_text(text,encoding='utf-8')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parent.parent)
    generate(parser.parse_args().root)
