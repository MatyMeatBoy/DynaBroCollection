"""Generate games/db2_glyph_text_table.inc from translations/db2special-en.json.

Each "glyph_text" entry: {"address", "before" (hex of the original glyph words, no
NUL), "lines": [english lines]}. The table carries the FNV-1a32 of the words as
they appear in the patched ROM (blank 0x0001 cells replaced by the 0x0002
placeholder) so the runtime hook only acts on a correctly patched ROM.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLACEHOLDER = 2


def patched_words(before_hex: str) -> bytes:
    raw = bytes.fromhex(before_hex)
    out = bytearray()
    for i in range(0, len(raw), 2):
        word = int.from_bytes(raw[i:i + 2], 'big')
        out += (PLACEHOLDER if word == 1 else word).to_bytes(2, 'big')
    return bytes(out)


def fnv32(data: bytes) -> int:
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xffffffff
    return h


def control_cells(before_hex: str) -> int:
    """Leading control words: even, below 0x120 and strictly increasing (see games/db2_glyph_text.c)."""
    raw = bytes.fromhex(before_hex)
    count = prev = 0
    for i in range(0, len(raw), 2):
        word = int.from_bytes(raw[i:i + 2], 'big')
        if not word or word & 1 or word >= 0x120 or word <= prev:
            break
        prev = word
        count += 1
    return count


def centered(text: str, entry: dict) -> str:
    chars = 2 * (len(entry['before']) // 4 - control_cells(entry['before']))
    spare = max(0, chars - len(text))
    return ' ' * (spare // 2) + text


def c_string(text: str) -> str:
    if not text.isascii() or any(ord(c) < 32 or c in '"\\' for c in text):
        raise ValueError(f'Unsupported character in {text!r}')
    return '"' + text + '"'


def render(catalog: dict) -> str:
    rows = []
    for entry in sorted(catalog.get('glyph_text', []), key=lambda e: e['address']):
        before = bytes.fromhex(entry['before'])
        if len(before) % 2 or not 1 <= len(before) // 2 <= 64:
            raise ValueError('Invalid glyph_text entry size')
        lines = entry['lines']
        if entry.get('align') == 'center':
            lines = [centered(line, entry) for line in lines]
        if not 1 <= len(lines) <= 6:
            raise ValueError('glyph_text needs 1..6 lines')
        rows.append('{0x%06X,%d,0x%08Xu,%d,{%s}},' % (
            entry['address'], len(before) // 2, fnv32(patched_words(entry['before'])), len(lines),
            ','.join(c_string(line) for line in lines)))
    return '/* Generated by tools/generate_db2_glyph_text.py; do not edit. */\n' + '\n'.join(rows) + ('\n' if rows else '')


def main():
    catalog = json.loads((ROOT / 'translations/db2special-en.json').read_text(encoding='utf-8'))
    (ROOT / 'games/db2_glyph_text_table.inc').write_text(render(catalog), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
